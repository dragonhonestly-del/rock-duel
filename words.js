// Функция нормализации слова (убирает ё, приводит к нижнему регистру, чистит пробелы)
function normalizeWord(str) {
    if (!str) return "";
    return str.toLowerCase().replace(/ё/g, 'е').trim();
}

// Категории для подсказок в интерфейсе
function getWordHint(word) {
    const w = normalizeWord(word);
    for (let tier in tiers) {
        if (tiers[tier].includes(w)) {
            if (tier == 1) return "Категория: Базовый элемент (Тир 1)";
            if (tier == 2) return "Категория: Техника и Стихия (Тир 2)";
            if (tier == 3) return "Категория: Космос и Физика (Тир 3)";
        }
    }
    return "Категория: Свободный объект / Материя";
}

// Локальный судья: проверяет, бьет ли новое слово предыдущее
function judgeMoveLocal(prevWord, newWord) {
    const p = normalizeWord(prevWord);
    const n = normalizeWord(newWord);

    if (n.length < 2) {
        return { valid: false, reason: "Слишком короткое слово!" };
    }

    // Запрет абстракций и читов
    const banned = ["бог", "вселенная", "всё", "все", "ничто", "бесконечность", "админ", "смерть", "время", "пространство"];
    if (banned.includes(n)) {
        return { valid: false, reason: `Абстракция или чит («${newWord}») запрещены!` };
    }

    // Самому себя бить нельзя
    if (p === n) {
        return { valid: false, reason: `Нельзя бить объект им же!` };
    }

    // 1. Проверяем словарь жестких контрмер
    if (counters[p] && counters[p].some(item => n.includes(item) || item.includes(n))) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» уничтожает и контрит «${prevWord}»!` };
    }
    
    // Обратная проверка (если игрок назвал то, что контрит предыдущее)
    if (counters[n] && counters[n].some(item => p.includes(item) || item.includes(p))) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» эффективно подавляет «${prevWord}»!` };
    }

    // 2. Логика по физике и тирам (Материальный прессинг)
    // Огонь тушится водой
    if ((p === "огонь" || p === "пламя" || p === "пожар") && (n.includes("вод") || n.includes("песок") || n.includes("углекислот") || n.includes("огнетушит"))) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» гасит пламя!` };
    }
    // Вода испаряется от жары/огня или замерзает
    if (p === "вода" && (n.includes("огон") || n.includes("солнц") || n.includes("лед") || n.includes("мороз") || n.includes("лаз"))) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» воздействует на воду!` };
    }
    // Металл режется лазером, плавится, ржавеет
    if ((p.includes("желез") || p.includes("сталь") || p.includes("металл") || p.includes("титан")) && (n.includes("кислот") || n.includes("лазер") || n.includes("термит") || n.includes("печь") || n.includes("ржавчин"))) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» разрушает структуру металла!` };
    }
    // Всё уничтожается черной дырой или антиматерией (кроме них самих)
    if ((n.includes("черн") && n.includes("дыр")) || n.includes("антивеществ") || n.includes("антиматери") || n.includes("сверхнов")) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» поглощает материю!` };
    }
    // Взрывчатка уничтожает любые физические предметы
    if (n.includes("динамит") || n.includes("бомб") || n.includes("ракет") || n.includes("взрыв")) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» разносит объект на куски!` };
    }
    // Техника ломается от воды, молотка, эмии
    if ((p.includes("компьютер") || p.includes("телефон") || p.includes("робот") || p.includes("спутник")) && (n.includes("вод") || n.includes("молот") || n.includes("эми") || n.includes("вирус"))) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» выводит электронику из строя!` };
    }

    // 3. Общая логика уничтожения по тирам (если объект явно старше/мощнее или из Тира выше)
    let pTier = 1, nTier = 1;
    for (let t in tiers) {
        if (tiers[t].some(item => p.includes(item))) pTier = parseInt(t);
        if (tiers[t].some(item => n.includes(item))) nTier = parseInt(t);
    }

    if (nTier > pTier) {
        return { valid: true, canonical: newWord, reason: `«${newWord}» технологически выше и мощнее («${prevWord}»)!` };
    }

    // Если связь совсем притянута и не найдена в базе
    return { 
        valid: false, 
        reason: `«${newWord}» физически не способно уничтожить «${prevWord}»!` 
    };
}

// Бот-мастер для одиночного режима подбирает ответный удар из базы
function getBotCounterMove(prevWord, usedWordsList) {
    const p = normalizeWord(prevWord);
    
    // Ищем, чем можно побить слово игрока
    for (let key in counters) {
        if (p.includes(key) || key.includes(p)) {
            for (let candidate of counters[key]) {
                if (!usedWordsList.includes(normalizeWord(candidate))) {
                    return { word: candidate, reason: `нашел уязвимость и ударил!` };
                }
            }
        }
    }

    // Иначе берем случайный мощный предмет из Тир 2 или Тир 3
    const pool = [...tiers[2], ...tiers[3]];
    for (let i = 0; i < 30; i++) {
        const randWord = pool[Math.floor(Math.random() * pool.length)];
        if (!usedWordsList.includes(normalizeWord(randWord))) {
            return { word: randWord, reason: `применил жесткую контрмеру!` };
        }
    }

    return null; // Если бот в тупике (игрок победил!)
}

